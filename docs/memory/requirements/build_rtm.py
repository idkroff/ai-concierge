        ("Историй без требований", f"=COUNTIF('US → SRS'!F2:F{s},\"НЕТ ТРЕБ.\")", 0),
        ("Незакрытых бизнес-целей", f"=COUNTIF('Бизнес-цели'!D2:D{len(GOALS) + 1},\"НЕ ЗАКРЫТА\")", 0),
