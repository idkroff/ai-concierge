def load_docs():
    prd = (SRC / "2.1_PRD.md").read_text()
    srs = (SRC / "2.2_SRS.md").read_text()
    us = (SRC / "2.3_UserStories.md").read_text()
    return prd, srs, us


def ids(field):
    return [x for x in re.findall(r"[A-Z]+-\d+(?:\.\d+)?", field)]


def validate():
    prd, srs, us = load_docs()
    errors = []
    srs_ids = re.findall(r"^\| ((?:N?FR)-\d\d) \|", srs, re.M)
    rtm_ids = [r[0] for r in REQS]
    if sorted(srs_ids) != sorted(rtm_ids):
        errors.append(f"SRS≠RTM: {set(srs_ids) ^ set(rtm_ids)}")
    # приоритеты SRS = RTM
    for rid, prio in re.findall(r"^\| ((?:N?FR)-\d\d) \|.*\| ([MS]) \|$", srs, re.M):
        row = next(r for r in REQS if r[0] == rid)
        if row[3] != prio:
            errors.append(f"приоритет {rid}: SRS {prio}, RTM {row[3]}")
    prd_ids = set(re.findall(r"^\| ((?:BG|M|P|G)-\d) \|", prd, re.M))
    # истории и AC из текста US
    stories = {}
    for block in re.split(r"^# (?=US-)", us, flags=re.M)[1:]:
        sid = block[:5]
        refs = re.search(r"^\*(.+)\*$", block, re.M).group(1)
        bg, reqs = refs.split("·")
        stories[sid] = {"bg": set(ids(bg)), "reqs": set(ids(reqs)),
                        "ac": set(re.findall(r"AC-\d\d\.\d", block))}
    summary = {m[0]: (set(ids(m[1])), set(ids(m[2])))
               for m in re.findall(r"^\| (US-\d\d) \|[^|]+\| ([^|]+) \| ([^|]+) \|", us, re.M)}
    for sid, s in stories.items():
        if summary.get(sid) != (s["bg"], s["reqs"]):
            errors.append(f"{sid}: сводка US не совпадает с телом истории")
    all_ac = set().union(*(s["ac"] for s in stories.values()))
    covered_ac = set()
    for rid, _, _, _, bg, met, us_f, ac_f, tc_f in REQS:
        for x in ids(bg) + ids(met):
            if x not in prd_ids:
                errors.append(f"{rid}: {x} нет в PRD")
        req_us = ids(us_f) if us_f.startswith("US") else []
        for u in req_us:
            if u not in stories:
                errors.append(f"{rid}: {u} не существует")
            elif rid not in stories[u]["reqs"]:
                errors.append(f"{rid}: в {u} нет ссылки на требование")
            elif not stories[u]["bg"] & set(ids(bg)):
                errors.append(f"{rid}: BG не пересекается с BG {u}")
        for a in ids(ac_f):
            if not any(a in stories[u]["ac"] for u in req_us):
                errors.append(f"{rid}: {a} не принадлежит его историям")
        tcs = {t[0]: t for t in TESTS}
        for t in ids(tc_f):
            if t not in tcs:
                errors.append(f"{rid}: {t} нет")
            elif rid not in ids(tcs[t][5]):
                errors.append(f"{rid}: {t} не ссылается обратно")
    for sid, s in stories.items():
        for rid in s["reqs"]:
            row = next((r for r in REQS if r[0] == rid), None)
            if row is None or sid not in row[6]:
                errors.append(f"{sid} → {rid}: нет в RTM")
    for t in TESTS:
        for rid in ids(t[5]):
            row = next((r for r in REQS if r[0] == rid), None)
            if row is None or t[0] not in ids(row[8]):
                errors.append(f"{t[0]} → {rid}: нет в RTM")
        for a in ids(t[6]):
            covered_ac.add(a)
            owners = {u for r in REQS if r[0] in ids(t[5]) for u in ids(r[6])}
            if not any(a in stories[u]["ac"] for u in owners if u in stories):
                errors.append(f"{t[0]}: {a} не относится к историям его требований")
    if all_ac - covered_ac:
        errors.append(f"AC без теста: {sorted(all_ac - covered_ac)}")
    used = {x for r in REQS for x in ids(r[4]) + ids(r[5])}
    if prd_ids - used:
        errors.append(f"цели/метрики PRD без требований: {prd_ids - used}")
    if errors:
        raise SystemExit("ОШИБКИ ТРАССИРОВКИ:\n" + "\n".join(errors))
    return len(all_ac)


def main():
    n_ac = validate()
    wb = xlsxwriter.Workbook(OUT)
    head = wb.add_format({"bold": True, "font_color": "#FFFFFF", "bg_color": "#1F3864",
                          "text_wrap": True, "valign": "top", "border": 1, "border_color": "#A6A6A6"})
    cell = wb.add_format({"text_wrap": True, "valign": "top", "border": 1, "border_color": "#A6A6A6"})
    ok = wb.add_format({"valign": "top", "border": 1, "border_color": "#A6A6A6", "font_color": "#006100", "bg_color": "#C6EFCE"})

    def sheet(title, header, rows, widths):
        ws = wb.add_worksheet(title)
        for c, (h, w) in enumerate(zip(header, widths)):
            ws.write(0, c, h, head)
            ws.set_column(c, c, w)
        for r, row in enumerate(rows, start=1):
            for c, v in enumerate(row):
                ws.write(r, c, v, cell)
        ws.freeze_panes(1, 1)
        ws.autofilter(0, 0, len(rows), len(header) - 1)
        return ws

    rtm = sheet("RTM",
                ["ID требования", "Тип", "Требование (SRS)", "Пр.", "↑ Бизнес-цель (PRD)", "↑ Метрика (PRD)",
                 "↑ User Story", "↑ Критерий приёмки", "↓ Тест-кейсы", "Статус теста (план)", "Проверка"],
                [r + ("Запланирован",) for r in REQS], [11, 6, 50, 5, 17, 20, 16, 20, 16, 13, 10])
    for i, r in enumerate(REQS, start=2):
        rtm.write_formula(f"K{i}", f'=IF(AND(LEFT(E{i},3)="BG-",COUNTIF(\'Тест-кейсы\'!A:A,LEFT(I{i},5))>0),"OK","СИРОТА")', ok, "OK")
    rtm.autofilter(0, 0, len(REQS), 10)

    tc = sheet("Тест-кейсы",
               ["ID теста", "Название", "Предусловия", "Шаги", "Ожидаемый результат", "↑ Требования",
                "↑ Критерий приёмки", "Проверка"],
               TESTS, [8, 24, 28, 38, 46, 14, 18, 10])
    for i, _ in enumerate(TESTS, start=2):
        tc.write_formula(f"H{i}", f'=IF(COUNTIF(RTM!I:I,"*"&A{i}&"*")>0,"OK","НЕТ ТРЕБ.")', ok, "OK")

